/** Get the council/LGA name for a district code. Returns undefined if not found. */
export function getDistrictName(code: string): string | undefined {
  return DISTRICT_MAP[code]
}

/** Get all district codes and names. */
export function getAllDistricts(): Array<{ code: string; name: string }> {
  return Object.entries(DISTRICT_MAP).map(([code, name]) => ({ code, name }))
}
